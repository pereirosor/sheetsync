export function getOccupationById(id: string): CoCOccupationDef | undefined {
  return COC_OCCUPATIONS.find(o => o.id === id);
}

export function getOccupationsForEra(era: '1920s' | 'modern'): CoCOccupationDef[] {
  return COC_OCCUPATIONS.filter(o =>
    o.era.includes('any') || o.era.includes(era),
  );
}

export function calcOccupationSkillPoints(
  occ: CoCOccupationDef,
  attrs: { edu: number; str: number; dex: number; app: number; pow: number },
): number {
  return occ.formulaCoeffs.reduce((sum, { attr, mult }) => sum + (attrs[attr] ?? 0) * mult, 0);
}
