export interface CoCOccupationDef {
  id: string;
  name: string;
  /** e.g. "EDU×4" | "EDU×2 + APP×2" */
  skillPointsFormula: string;
  /** parsed coefficients for computation */
  formulaCoeffs: { attr: 'edu' | 'str' | 'dex' | 'app' | 'pow'; mult: number }[];
  creditRating: [number, number];
  /** Skill IDs from which occupation points must be spent (8 canonical skills) */
  occupationSkills: string[];
  /** Extra free-pick slots inside the occupation list ("any X skills") */
  freeSlots: number;
  era: ('1920s' | 'modern' | 'any')[];
}

function f(
  ...pairs: [attr: 'edu' | 'str' | 'dex' | 'app' | 'pow', mult: number][]
): { attr: 'edu' | 'str' | 'dex' | 'app' | 'pow'; mult: number }[] {
  return pairs.map(([attr, mult]) => ({ attr, mult }));
}

